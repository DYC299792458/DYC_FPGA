$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

# Chinese glyph set for the on-screen recognition label.
#   0 jian 0x68C0, 1 ce 0x6D4B, 2 dao 0x5230, 3 yuan 0x5706, 4 xing 0x5F62,
#   5 ju   0x77E9, 6 wei 0x672A, 7 shi 0x8BC6, 8 bie 0x522B, 9 san 0x4E09,
#  10 jiao 0x89D2, 11 mu 0x76EE, 12 biao 0x6807
$glyphs = @(
  @{n='jian'; c=0x68C0}, @{n='ce';  c=0x6D4B}, @{n='dao'; c=0x5230},
  @{n='yuan'; c=0x5706}, @{n='xing';c=0x5F62}, @{n='ju';  c=0x77E9},
  @{n='wei';  c=0x672A}, @{n='shi'; c=0x8BC6}, @{n='bie'; c=0x522B},
  @{n='san';  c=0x4E09}, @{n='jiao';c=0x89D2}, @{n='mu';  c=0x76EE},
  @{n='biao'; c=0x6807}
)

# Render one glyph, return an array of 16 strings of '.'/'#' (row 0 = top).
# Returning strings avoids PowerShell unrolling multidimensional arrays.
function Get-GlyphRows([int]$code, [string]$mode) {
  $ch  = [string][char]$code
  $CAN = 64
  $bmp = New-Object -TypeName System.Drawing.Bitmap -ArgumentList $CAN, $CAN
  $gr  = [System.Drawing.Graphics]::FromImage($bmp)
  $gr.Clear([System.Drawing.Color]::Black)

  if ($mode -eq 'strike') {
    $gr.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
    $font = New-Object -TypeName System.Drawing.Font -ArgumentList @('SimSun', [single]16, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
    $gr.DrawString($ch, $font, [System.Drawing.Brushes]::White, 16, 16)
    $ss = 1
    $thr = 127
  } else {
    $gr.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $font = New-Object -TypeName System.Drawing.Font -ArgumentList @('SimSun', [single]48, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
    $gr.DrawString($ch, $font, [System.Drawing.Brushes]::White, 8, 8)
    $ss = 3
    $thr = 150
  }
  $gr.Dispose()

  $n = [int]($CAN / $ss)
  $src = New-Object 'bool[,]' $n, $n
  for ($y = 0; $y -lt $n; $y++) {
    for ($x = 0; $x -lt $n; $x++) {
      $acc = 0
      for ($dy = 0; $dy -lt $ss; $dy++) {
        for ($dx = 0; $dx -lt $ss; $dx++) {
          $acc += $bmp.GetPixel(($x * $ss) + $dx, ($y * $ss) + $dy).R
        }
      }
      if (($acc / ($ss * $ss)) -gt $thr) { $src[$x, $y] = $true }
    }
  }
  $bmp.Dispose()

  $minx = 999; $maxx = -1; $miny = 999; $maxy = -1
  for ($y = 0; $y -lt $n; $y++) {
    for ($x = 0; $x -lt $n; $x++) {
      if ($src[$x, $y]) {
        if ($x -lt $minx) { $minx = $x }
        if ($x -gt $maxx) { $maxx = $x }
        if ($y -lt $miny) { $miny = $y }
        if ($y -gt $maxy) { $maxy = $y }
      }
    }
  }

  $grid = New-Object 'bool[,]' 16, 16
  if ($maxx -ge 0) {
    $gw = $maxx - $minx + 1
    $gh = $maxy - $miny + 1
    $ox = [int][math]::Floor((16 - $gw) / 2) - $minx
    $oy = [int][math]::Floor((16 - $gh) / 2) - $miny
    for ($y = $miny; $y -le $maxy; $y++) {
      for ($x = $minx; $x -le $maxx; $x++) {
        if ($src[$x, $y]) {
          $nx = $x + $ox; $ny = $y + $oy
          if ($nx -ge 0 -and $nx -lt 16 -and $ny -ge 0 -and $ny -lt 16) { $grid[$nx, $ny] = $true }
        }
      }
    }
  }

  $rows = @()
  for ($y = 0; $y -lt 16; $y++) {
    $line = ''
    for ($x = 0; $x -lt 16; $x++) {
      if ($grid[$x, $y]) { $line += '#' } else { $line += '.' }
    }
    $rows += $line
  }
  return $rows
}

# Build both variants for every glyph. Wrap in "," so each glyph stays one element.
$strike = @()
$aa = @()
foreach ($g in $glyphs) {
  $strike += ,(Get-GlyphRows $g.c 'strike')
  $aa     += ,(Get-GlyphRows $g.c 'aa')
}

# Sanity check: fail loudly rather than emitting a broken ROM.
for ($i = 0; $i -lt $glyphs.Count; $i++) {
  $on = 0
  foreach ($r in $strike[$i]) { $on += ($r.ToCharArray() | Where-Object { $_ -eq '#' }).Count }
  if ($on -lt 20 -or $on -gt 220) {
    throw ("glyph " + $glyphs[$i].n + " has suspicious ink coverage: " + $on + " px")
  }
  Write-Output ("  " + $glyphs[$i].n + " ink=" + $on)
}

# --- write the Verilog ROM from the 'strike' variant -------------------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// -----------------------------------------------------------------------------")
[void]$sb.AppendLine("// font_cn_rom.v : 16x16 dot-matrix Chinese font ROM (13 glyphs, SimSun 16px)")
[void]$sb.AppendLine("// Auto-generated by tools/genfont.ps1 - do not edit by hand.")
[void]$sb.AppendLine("// Each glyph is 16 rows x 16 columns; row 0 is the top scan line.")
[void]$sb.AppendLine("// The 16-bit row word is MSB-first: bit[15] is the left-most pixel.")
[void]$sb.AppendLine("// -----------------------------------------------------------------------------")
[void]$sb.AppendLine("``timescale 1ns/1ps")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("module font_cn_rom (")
[void]$sb.AppendLine("    input  wire [3:0]  char_idx,   // 0..12, see map below")
[void]$sb.AppendLine("    input  wire [3:0]  row,        // 0..15 scan line, 0 = top")
[void]$sb.AppendLine("    output reg  [15:0] bits        // bit15 = left-most pixel")
[void]$sb.AppendLine(");")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("// Glyph index map:")
for ($i = 0; $i -lt $glyphs.Count; $i++) {
  [void]$sb.AppendLine("//   $i : U+" + $glyphs[$i].c.ToString('X4') + "  (" + $glyphs[$i].n + ")")
}
[void]$sb.AppendLine("")
[void]$sb.AppendLine("always @(*) begin")
[void]$sb.AppendLine("    case ({char_idx, row})")
for ($i = 0; $i -lt $glyphs.Count; $i++) {
  for ($y = 0; $y -lt 16; $y++) {
    $hi = 0; $lo = 0
    for ($x = 0; $x -lt 16; $x++) {
      if ($strike[$i][$y][$x] -eq '#') {
        if ($x -lt 8) { $hi = $hi -bor (1 -shl (7 - $x)) } else { $lo = $lo -bor (1 -shl (15 - $x)) }
      }
    }
    $idx = ($i * 16) + $y
    [void]$sb.AppendLine(("        8'd{0,-3}: bits = 16'h{1:X4};   // {2} row {3}" -f $idx, (($hi -shl 8) -bor $lo), $glyphs[$i].n, $y))
  }
}
[void]$sb.AppendLine("        default: bits = 16'h0000;")
[void]$sb.AppendLine("    endcase")
[void]$sb.AppendLine("end")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("endmodule")
[System.IO.File]::WriteAllText("C:\Users\Liangyaxuan\fpga_work\out\font_cn_rom.v", $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))

# --- render a preview PNG ---------------------------------------------
$S = 10
$gap = 4
$cols = 5
$rowsN = [int][math]::Ceiling($glyphs.Count / $cols)
$cellW = (16 * $S) + $gap
$cellH = (16 * $S) + $gap
$gridW = $cols * $cellW
$gridH = $rowsN * $cellH

$msgs = @(
  @(0,1,2,3,4),
  @(0,1,2,5,4),
  @(0,1,2,9,10,4),
  @(6,7,8),
  @(11,12)
)
$msgLineH = (16 * $S) + 12
$msgW = 0
foreach ($m in $msgs) {
  $w = ($m.Count * 16 * $S) + (($m.Count - 1) * $S)
  if ($w -gt $msgW) { $msgW = $w }
}
$totalW = [int][math]::Max($gridW, $msgW) + 16
$totalH = $gridH + ($rowsN * (16 * 5 + $gap)) + ($msgs.Count * $msgLineH) + 24

$out = New-Object -TypeName System.Drawing.Bitmap -ArgumentList $totalW, $totalH
$og  = [System.Drawing.Graphics]::FromImage($out)
$og.Clear([System.Drawing.Color]::FromArgb(20, 20, 28))

$white  = [System.Drawing.Brushes]::White
$yellow = [System.Drawing.Brushes]::Gold

function Draw-Rows($gr, $lines, $ox, $oy, $s, $br) {
  for ($y = 0; $y -lt 16; $y++) {
    for ($x = 0; $x -lt 16; $x++) {
      if ($lines[$y][$x] -eq '#') {
        $gr.FillRectangle($br, $ox + ($x * $s), $oy + ($y * $s), $s, $s)
      }
    }
  }
}

for ($i = 0; $i -lt $glyphs.Count; $i++) {
  $cx = (($i % $cols) * $cellW) + 8
  $cy = ([int][math]::Floor($i / $cols) * $cellH) + 8
  Draw-Rows $og $strike[$i] $cx $cy $S $white
}

# anti-aliased variant comparison strip
$S2 = 5
$aaY = $gridH + 8
for ($i = 0; $i -lt $glyphs.Count; $i++) {
  $cx = (($i % $cols) * ((16 * $S2) + $gap)) + 8
  $cy = $aaY + ([int][math]::Floor($i / $cols) * ((16 * $S2) + $gap))
  Draw-Rows $og $aa[$i] $cx $cy $S2 $yellow
}

$lineY = $aaY + ($rowsN * ((16 * $S2) + $gap)) + 16
foreach ($m in $msgs) {
  $x = 8
  foreach ($gi in $m) {
    Draw-Rows $og $strike[$gi] $x $lineY $S $white
    $x += (16 * $S) + $S
  }
  $lineY += $msgLineH
}

$og.Dispose()
$out.Save("C:\Users\Liangyaxuan\fpga_work\out\font_preview.png", [System.Drawing.Imaging.ImageFormat]::Png)
$out.Dispose()

Write-Output "wrote font_cn_rom.v and font_preview.png"
